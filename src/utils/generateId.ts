// آی‌دی یکتا برای رکوردهای mock. فقط Date.now() کافی نیست - اگه دو تا آیتم
// دقیقاً تو یه میلی‌ثانیه ساخته بشن (مثلاً دابل-کلیک رو دکمه‌ی ثبت)، آی‌دی
// یکسان می‌گیرن و بعداً ویرایش/حذف یکی، هر دو رو تحت تاثیر قرار می‌ده.
export function generateId(): string {
  return `${Date.now()}-${Math.random().toString(36).slice(2, 8)}`;
}
